abstract class ExportApkTask : DefaultTask() {
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val apkDirectory: DirectoryProperty

    @get:Internal
    abstract val builtArtifactsLoader: Property<BuiltArtifactsLoader>

    @get:OutputFile
    abstract val destination: RegularFileProperty

    @TaskAction
    fun export() {
        val artifacts = checkNotNull(builtArtifactsLoader.get().load(apkDirectory.get())) {
            "생성된 APK 정보를 찾지 못했습니다."
        }
        val apk = checkNotNull(artifacts.elements.singleOrNull()) {
            "제출용 APK는 분할하지 않은 파일 하나여야 합니다."
        }
        val target = destination.get().asFile
        target.parentFile.mkdirs()
        File(apk.outputFile).copyTo(target, overwrite = true)
        logger.lifecycle("APK 생성: ${target.absolutePath}")
    }
}

