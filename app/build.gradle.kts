val verifyReleaseSigning by tasks.registering {
    doLast {
        check(hasReleaseSigning) {
            "릴리스 서명 설정이 필요합니다. .signing/release.properties에 " +
                "storeFile, storePassword, keyAlias, keyPassword를 설정하세요. README.md를 참고하세요."
        }
        check(rootProject.file(releaseSigning.getProperty("storeFile")).isFile) {
            "릴리스 서명 키스토어를 찾지 못했습니다. .signing/release.properties의 storeFile을 확인하세요."
        }
    }
}

tasks.matching { it.name == "preReleaseBuild" }.configureEach {
    dependsOn(verifyReleaseSigning)
}

androidComponents {
    onVariants { variant ->
        val variantName = variant.name.replaceFirstChar { it.uppercaseChar() }
        val exportApk = tasks.register<ExportApkTask>("export${variantName}Apk") {
            group = "build"
            description = "${variant.name} APK를 저장소의 apk/ 폴더에 저장합니다."
            builtArtifactsLoader.set(variant.artifacts.getBuiltArtifactsLoader())
            destination.set(rootProject.layout.projectDirectory.file("apk/이무희_tirelog_${variant.name}.apk"))
        }
        variant.artifacts.use(exportApk)
            .wiredWith(ExportApkTask::apkDirectory)
            .toListenTo(SingleArtifact.APK)
    }
}

